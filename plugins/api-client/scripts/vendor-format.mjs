import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
const require = createRequire(import.meta.url);
const destination = new URL("../shared/vendor/", import.meta.url);
await build({
  stdin: {
    contents: `import {format} from "prettier/standalone";
import * as html from "prettier/plugins/html";
import * as postcss from "prettier/plugins/postcss";
import * as babel from "prettier/plugins/babel";
import * as estree from "prettier/plugins/estree";
export function formatMarkup(source) { return format(source, {parser:"html",plugins:[html,postcss,babel,estree],tabWidth:2,htmlWhitespaceSensitivity:"ignore",printWidth:100}); }`,
    resolveDir: process.cwd(),
  },
  outfile: new URL("format.gen.ts", destination).pathname,
  bundle: true,
  format: "esm",
  platform: "browser",
  minify: true,
  legalComments: "inline",
  banner: {
    js: "// @ts-nocheck\n/* oxlint-disable */\n// Generated by scripts/vendor-format.mjs. See FORMAT_LICENSE.txt.",
  },
});
await writeFile(
  new URL("FORMAT_LICENSE.txt", destination),
  await readFile(path.join(path.dirname(require.resolve("prettier/package.json")), "LICENSE")),
);
