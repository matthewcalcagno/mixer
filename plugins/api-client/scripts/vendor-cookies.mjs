import { build } from "esbuild";
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Built-in resources live outside app.asar, where npm dependencies cannot resolve.
// Regenerate this dependency-only bundle when updating tough-cookie or its public suffix list.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(import.meta.url);
const destination = path.join(root, "api-client/shared/vendor");
await build({
  stdin: {
    contents: `import { CookieJar } from "tough-cookie";
function jarFrom(serialized) { return serialized ? CookieJar.fromJSON(serialized) : new CookieJar(); }
export function cookieHeader(serialized, url) { return jarFrom(serialized).getCookieStringSync(url); }
export function mergeCookies(serialized, updates) {
 const jar = jarFrom(serialized);
 for (const cookie of updates) jar.setCookieSync(cookie.value, cookie.url, {ignoreError:true});
 return JSON.stringify(jar.toJSON());
}`,
    resolveDir: root,
  },
  outfile: path.join(destination, "cookie-jar.gen.ts"),
  bundle: true,
  format: "esm",
  platform: "browser",
  minify: true,
  legalComments: "inline",
  banner: {
    js: "// @ts-nocheck\n/* oxlint-disable */\n// Generated by scripts/vendor-cookies.mjs. See THIRD_PARTY_NOTICES.txt.\n",
  },
});
const notices = [];
for (const name of ["tough-cookie", "tldts", "tldts-core"]) {
  let packageRoot = path.dirname(require.resolve(name));
  while (true) {
    try {
      const candidate = JSON.parse(await readFile(path.join(packageRoot, "package.json"), "utf8"));
      if (candidate.name === name) break;
    } catch {
      /* Package entry points can be nested below their manifest. */
    }
    const parent = path.dirname(packageRoot);
    if (parent === packageRoot) throw new Error(`Cannot find package manifest for ${name}`);
    packageRoot = parent;
  }
  const manifest = JSON.parse(await readFile(path.join(packageRoot, "package.json"), "utf8"));
  notices.push(
    `${name} ${manifest.version}\n\n${await readFile(path.join(packageRoot, "LICENSE"), "utf8")}`,
  );
}
await writeFile(path.join(destination, "THIRD_PARTY_NOTICES.txt"), notices.join("\n\n---\n\n"));
