import { build as bundle } from "esbuild";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { compressedSyntaxRegistry, monacoLanguageRegistrations } from "./syntax-assets.mjs";
const require = createRequire(import.meta.url);
process.chdir(fileURLToPath(new URL("../", import.meta.url)));
import { readFile, mkdir, writeFile } from "node:fs/promises";

const worker = await bundle({
  entryPoints: [require.resolve("monaco-editor/esm/vs/editor/editor.worker.js")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  minify: true,
});
const workerSource = worker.outputFiles[0].text;
const jsonWorker = await bundle({
  entryPoints: [require.resolve("monaco-editor/esm/vs/language/json/json.worker.js")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  minify: true,
});
// Monaco 0.56 maps an empty original to a deleted blank line. Use an empty
// line range so inline additions do not render a phantom deletion or red margin.
const emptyOriginalFix = {
  name: "empty-original-diff",
  setup(build) {
    build.onLoad({ filter: /[/\\]diffProviderFactoryService\.js$/ }, async ({ path }) => {
      const source = await readFile(path, "utf8");
      const before =
        "new DetailedLineRangeMapping(new LineRange(1, 2), new LineRange(1, modified.getLineCount() + 1)";
      if (!source.includes(before))
        throw new Error("Review Monaco's empty-original diff mapping after upgrading");
      return {
        contents: source.replace(
          before,
          "new DetailedLineRangeMapping(new LineRange(1, 1), new LineRange(1, modified.getLineCount() + 1)",
        ),
        loader: "js",
      };
    });
  },
};
const compressedLanguages = await compressedSyntaxRegistry();
const languageRegistrations = await monacoLanguageRegistrations();
const syntaxRegistry = {
  name: "offline-textmate-registry",
  setup(build) {
    build.onResolve({ filter: /^shiki\/langs$/ }, () => ({
      path: "syntax-registry",
      namespace: "offline-textmate",
    }));
    build.onLoad({ filter: /.*/, namespace: "offline-textmate" }, () => ({
      contents: compressedLanguages,
      loader: "js",
    }));
  },
};
const result = await bundle({
  absWorkingDir: process.cwd(),
  entryPoints: ["scripts/editor-entry.mjs"],
  bundle: true,
  write: false,
  outfile: "editor.js",
  format: "iife",
  platform: "browser",
  minify: true,
  plugins: [emptyOriginalFix, syntaxRegistry],
  loader: { ".ttf": "dataurl" },
  define: {
    __EDITOR_WORKER__: JSON.stringify(workerSource),
    __JSON_WORKER__: JSON.stringify(jsonWorker.outputFiles[0].text),
    __MONACO_LANGUAGES__: JSON.stringify(languageRegistrations),
  },
});
const javascript = result.outputFiles.find((file) => file.path.endsWith(".js"))?.text;
const css = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text;
if (!javascript || !css) throw new Error("Missing Monaco JavaScript or stylesheet");
const policy =
  "default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval' blob:; style-src 'unsafe-inline'; worker-src blob:; font-src data:; img-src data: blob:; connect-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'";
const html = `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${policy}"><meta name="viewport" content="width=device-width, initial-scale=1"><style>html,body,#editor{margin:0;width:100%;height:100%;overflow:hidden}html{background:transparent}#editor{visibility:hidden}${css}</style></head><body><div id="editor"></div><script>${javascript.replaceAll("</script", "<\\/script")}</script></body></html>`;
await mkdir("client/generated", { recursive: true });
await writeFile(
  "client/generated/editor-html.ts",
  `// Generated by node plugins/source-control/scripts/build-editor.mjs. Do not edit.\nexport const editorHtml = ${JSON.stringify(html)};\n`,
);
await writeFile(
  "client/generated/MONACO-LICENSE",
  await readFile(
    resolve(dirname(require.resolve("monaco-editor/package.json")), "LICENSE"),
    "utf8",
  ),
);
await writeFile(
  "client/generated/DOMPURIFY-LICENSE",
  await readFile(resolve(dirname(require.resolve("dompurify")), "../LICENSE"), "utf8"),
);
console.log(`Built offline Monaco diff editor: ${Math.round(Buffer.byteLength(html) / 1024)} KiB`);
